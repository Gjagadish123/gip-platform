// `npm run db:seed` (repo root), then `npm run db:reset`. Writes three files from the admin's demo data:
// - supabase/seed.sql: projects, units and activity of the four live layout projects (SEED), this phase's working
//   set. Data only, so it is also what "Going live" step 4 runs in the hosted SQL editor.
// - supabase/seed.catalogue.sql: the client's other real projects (CATALOGUE minus SEED; the sample project is left
//   out), not loaded by db:reset. Add it to [db.seed] in supabase/config.toml, or run it, when they are wanted.
// - supabase/seed.local-admin.sql: a local admin login with a random password, gitignored (the repo is public).
//   Kept if it already exists, so the password doesn't change on every run.
// Rows go through the same mapping (src/lib/supabase/rows.ts) and SQL helper (private.insert_units) as the app.
import { randomBytes, randomUUID } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { CATALOGUE, SEED } from '../src/lib/mock';
import { projectToRow, unitPayload } from '../src/lib/supabase/rows';

const DATA_FILE = new URL('../../supabase/seed.sql', import.meta.url);
const CATALOGUE_FILE = new URL('../../supabase/seed.catalogue.sql', import.meta.url);
const ADMIN_FILE = new URL('../../supabase/seed.local-admin.sql', import.meta.url);

const json = (v: unknown) => `$seed$${JSON.stringify(v)}$seed$::jsonb`;
// Every column but the generated public_content.
const PROJECT_COLS = 'id, slug, name, type_id, lifecycle, publish_state, homepage_slot, sort_order, content, '
  + 'inventory_updated_at, status_sample, sample, created_at, updated_at, published_at';
const noon = (date: string | undefined) => (date ? `${date}T12:00:00+05:30` : null);

const live = SEED.projects.filter((p) => !p.sample);
const others = CATALOGUE.projects.filter((p) => !p.sample && !live.some((l) => l.id === p.id));

function seedSql(projects: typeof live, note: string): string {
  const out: string[] = [
    '-- GENERATED by admin/scripts/gen-seed.ts (`npm run db:seed`). Edit the script, not this file.',
    `-- ${note}`,
    `-- Projects: ${projects.map((p) => p.name).join(', ')}. Data only: no users.`,
    '',
  ];
  for (const p of projects) {
  const row = {
    ...projectToRow(p),
    inventory_updated_at: p.inventoryUpdatedAt ?? null,
    status_sample: !!p.statusSample,
    sample: !!p.sample,
    created_at: noon(p.publishing.publishedAt ?? p.publishing.updatedAt),
    updated_at: noon(p.publishing.updatedAt),
    published_at: noon(p.publishing.publishedAt),
  };
  const units = CATALOGUE.units[p.id] ?? [];
  const activity = CATALOGUE.activity.filter((a) => a.projectId === p.id).map((a) => ({
    at: a.at, actor_name: a.by, project_id: a.projectId, kind: a.kind, message: a.message,
    batch_id: a.batchId ?? null, unit_numbers: a.unitNumbers ?? null, to_status: a.to ?? null,
  }));
  out.push(
    `-- ${p.name}: ${units.length} units (with their history), ${activity.length} activity entries`,
    `insert into public.projects (${PROJECT_COLS}) select ${PROJECT_COLS} from jsonb_populate_recordset(null::public.projects, ${json([row])});`,
    `select private.insert_units('${p.id}', ${json(units.map((u) => unitPayload(u)))}, true);`,
    `insert into public.activity (at, actor_name, project_id, kind, message, batch_id, unit_numbers, to_status)
select at, actor_name, project_id, kind, message, batch_id, unit_numbers, to_status
from jsonb_populate_recordset(null::public.activity, ${json(activity)});`,
    '',
  );
  }
  return out.join('\n');
}
writeFileSync(DATA_FILE, seedSql(live, "The four projects on the website's live layouts page (loaded by `npm run db:reset`)."));
writeFileSync(CATALOGUE_FILE, seedSql(others, "The client's other projects: not loaded by db:reset. Run after seed.sql when they are wanted."));

if (!existsSync(ADMIN_FILE)) {
  const id = randomUUID(), email = 'admin@gip.local', password = randomBytes(12).toString('base64url');
  writeFileSync(ADMIN_FILE, `-- GENERATED by admin/scripts/gen-seed.ts. LOCAL STACK ONLY, gitignored: never run this on a hosted project.
-- Local admin login: ${email} / ${password}
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data,
  raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', '${id}', 'authenticated', 'authenticated', '${email}',
  extensions.crypt('${password}', extensions.gen_salt('bf')), now(),
  '{"provider": "email", "providers": ["email"], "role": "admin"}', '{"name": "Admin"}', now(), now(), '', '', '', '');
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), '${id}', '${id}', '{"sub": "${id}", "email": "${email}", "email_verified": true}', 'email', now(), now(), now());
`);
  console.log(`Wrote supabase/seed.local-admin.sql: local login ${email} (password in that file's header).`);
}
console.log(`Wrote supabase/seed.sql: ${live.map((p) => p.name).join(', ')}.`);
console.log(`Wrote supabase/seed.catalogue.sql (not loaded by db:reset): ${others.length} other projects.`);
